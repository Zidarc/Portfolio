// Converts the Hershey Sans 1-stroke SVG font into the compact stroke table used by the crayon engine.
//
// Usage:
//   1. Download the `hersheytext` npm tarball and extract svg_fonts/HersheySans1.svg
//   2. node scripts/build-font.mjs path/to/HersheySans1.svg
//
// Output: src/crayon/font/hersheySans.ts
// Units: 1 = cap height, y grows downward, baseline at y = 0, each glyph shifted so its left edge is x = 0.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const CAP_HEIGHT = 662;
const src = readFileSync(process.argv[2], 'utf8');

const decode = (s) =>
  s
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&apos;/g, "'")
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCharCode(parseInt(h, 16)));

const round = (n) => Math.round(n * 1000) / 1000;
const glyphs = {};

for (const m of src.matchAll(/<glyph\s+unicode="([^"]*)"[^>]*?(?:\sd="([^"]*)")?\s*\/>/g)) {
  const ch = decode(m[1]);
  if (ch.length !== 1) continue;
  const code = ch.charCodeAt(0);
  if (code < 33 || code > 126 || !m[2]) continue;

  const strokes = [];
  let current = null;
  for (const [, cmd, x, y] of m[2].matchAll(/([ML])\s*(-?[\d.]+)\s+(-?[\d.]+)/g)) {
    if (cmd === 'M') {
      current = [];
      strokes.push(current);
    }
    current.push(Number(x) / CAP_HEIGHT, -Number(y) / CAP_HEIGHT);
  }

  const xs = strokes.flatMap((s) => s.filter((_, i) => i % 2 === 0));
  const minX = Math.min(...xs);
  const width = Math.max(...xs) - minX;
  glyphs[ch] = {
    w: round(width),
    s: strokes.map((s) => s.map((v, i) => round(i % 2 === 0 ? v - minX : v))),
  };
}

const out = `// Generated by scripts/build-font.mjs. Do not edit by hand.
//
// Glyph data: Hershey Sans 1-stroke, via the hersheytext package (Evil Mad Scientist SVG conversion).
// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
// U. S. National Bureau of Standards.
// The format of the Font data in this distribution was originally created by
// James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica, MA 01821.
//
// Units: 1 = cap height, y down, baseline y = 0. Each stroke is a flat [x0, y0, x1, y1, ...] list.

export interface Glyph {
  /** Ink width (left edge is always 0). */
  w: number;
  /** Pen strokes in drawing order. */
  s: number[][];
}

export const glyphs: Record<string, Glyph> = ${JSON.stringify(glyphs)};
`;

mkdirSync('src/crayon/font', { recursive: true });
writeFileSync('src/crayon/font/hersheySans.ts', out);
console.log(`Wrote ${Object.keys(glyphs).length} glyphs`);
